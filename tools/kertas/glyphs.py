"""Kertas: every glyph as a skeleton, the line a pen would travel.

Units: 1000 per em. Baseline 0, x-height 520, caps and figures 700,
ascenders 750, descenders -210. Each glyph is a list of strokes. A stroke is a
list of points the pen passes through; sharp turns are split into separate
strokes by the builder, so every joint ends up soft and round.

Helpers:
  ln(*pts)                 straight segments through the points
  pth(*parts)              points and arc()/spl() lists joined into one stroke
  arc(cx,cy,rx,ry,a0,a1)   ellipse arc, degrees, counter-clockwise is positive
  ell(cx,cy,rx,ry)         a closed loop
  spl(*pts)                a smooth curve through the points (Catmull-Rom)
  dot(x,y)                 a round mark, slightly heavier than the line
"""

import math

X, C, A, D = 520, 700, 750, -210


def arc(cx, cy, rx, ry, a0, a1, step=3):
    n = max(2, int(abs(a1 - a0) / step) + 1)
    return [(cx + rx * math.cos(math.radians(a0 + (a1 - a0) * i / (n - 1))),
             cy + ry * math.sin(math.radians(a0 + (a1 - a0) * i / (n - 1)))) for i in range(n)]


def spl(*pts, n=14):
    p = [pts[0]] + list(pts) + [pts[-1]]
    out = []
    for i in range(1, len(p) - 2):
        p0, p1, p2, p3 = p[i - 1], p[i], p[i + 1], p[i + 2]
        for k in range(n):
            t = k / n
            t2, t3 = t * t, t * t * t
            out.append(tuple(0.5 * (2 * p1[j] + (-p0[j] + p2[j]) * t + (2 * p0[j] - 5 * p1[j] + 4 * p2[j] - p3[j]) * t2
                                    + (-p0[j] + 3 * p1[j] - 3 * p2[j] + p3[j]) * t3) for j in range(2)))
    out.append(pts[-1])
    return out


def pth(*parts):
    pts = []
    for part in parts:
        if isinstance(part, list):
            pts.extend(part)
        else:
            pts.append(part)
    return {'pts': pts}


def ln(*pts):
    return {'pts': list(pts)}


def ell(cx, cy, rx, ry):
    return {'pts': arc(cx, cy, rx, ry, 90, 450)[:-1], 'closed': True}


def dot(x, y):
    return {'pts': [(x, y - 3), (x, y + 3)], 'w': 1.45, 'dot': True}


def curve(*pts):
    return {'pts': spl(*pts)}


